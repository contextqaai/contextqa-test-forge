// Repository-owned fixture. Scripted review labels must never approve customer requirements.
import {mkdir, writeFile} from 'node:fs/promises';
import {performance} from 'node:perf_hooks';
import {sha} from '../src/sources.js';
import {approve} from '../src/contracts.js';
import {exportProject} from '../src/exporters.js';
import {proposeMaintenance, approveMaintenance, exportMaintenance} from '../src/maintenance.js';
import {builderFixture} from './builder-fixture.js';
const started = performance.now();
const args = process.argv.slice(2);
const out = args[0] && !args[0].startsWith('--') ? args.shift() : `output/builder-${Date.now()}`;
if (args.length > 1 || args.length === 1 && args[0] !== '--page-object') throw new Error('Use a new output directory and optional --page-object');
const pattern = args.includes('--page-object') ? 'page-object' : 'inline';
await mkdir(out, {mode: 0o700});
const save = (name, value) => writeFile(`${out}/${name}.json`, JSON.stringify(value, null, 2) + '\n', {flag: 'wx', mode: 0o600});
const {source, before:contract, after, apps} = builderFixture({pattern});
for (const [name, content] of Object.entries(apps)) await writeFile(`${out}/${name}.html`, content, {flag: 'wx', mode: 0o600});
const reviewer = 'Repository synthetic reviewer (scripted fixture, not customer approval)';
const review = approve(contract, reviewer, source);
await save('source', source); await save('before', contract); await save('before-approval', review);
await exportProject(contract, review, 'playwright', `${out}/baseline`);
await exportProject(contract, review, 'playwright', `${out}/stale-locator`);
const negative = structuredClone(contract);
negative.tests[0].steps[3].value = 'Approved';
await exportProject(negative, approve(negative, reviewer, source), 'playwright', `${out}/negative-rule`);
const proposal = proposeMaintenance({before: contract, after, source, classification: 'locator-drift', reason: 'Synthetic UI changed the submit button ID; original business assertions remain unchanged', evidence: [{kind: 'local-artifact', ref: 'stale-locator.runner.json'}]});
const repairApproval = approveMaintenance(proposal, reviewer);
await save('after', after); await save('maintenance-proposal', proposal); await save('maintenance-approval', repairApproval);
await exportMaintenance(proposal, repairApproval, `${out}/repaired`);
await exportMaintenance(proposal, repairApproval, `${out}/behavior-defect`);
const attemptedWeakening = structuredClone(after); attemptedWeakening.tests[0].steps[3].value = 'Approved';
await save('behavior-escalation', proposeMaintenance({before: after, after: attemptedWeakening, source, classification: 'behavior-change', reason: 'The app permits an unapproved expense; changing the expected result would hide the defect', evidence: [{kind: 'local-artifact', ref: 'behavior-defect.runner.json'}]}));
await save('manifest', {schema: 1, scenario: 'repository-owned-synthetic-expense-policy', pattern, ...(pattern === 'page-object' ? {indent:2} : {}), preparedAt: new Date().toISOString(), generationDurationMs: Math.round(performance.now() - started), beforeSha: sha(contract), afterSha: sha(after), modelCalls: 0, inputTokens: 0, outputTokens: 0, usageSource: 'no-model-calls', contextqaCalls: 0, nativeIds: 'synthetic-do-not-submit', executed: false, businessOutcome: 'not-measured', contextqaHealingVerified: false});
console.log(JSON.stringify({output: out, pattern, prepared: true, executed: false, modelCalls: 0, contextqaCalls: 0}));
